import assert from 'node:assert/strict';
import { createRequestScopeState } from '../app/workspace/use-request-scope';

const scope = createRequestScopeState();
scope.update('article-a', '原文');
const layoutA = scope.begin('layout');
const imageA = scope.begin('image');
assert.equal(layoutA(), true);
assert.equal(imageA(), true, 'different requests may coexist');
const layoutB = scope.begin('layout');
assert.equal(layoutA(), false, 'latest request wins within a channel');
assert.equal(layoutA.signal.aborted, true, 'superseded network work is aborted');
assert.equal(layoutB(), true);
assert.equal(imageA(), true, 'another channel stays current');
scope.update('article-b', '原文');
assert.equal(layoutB(), false, 'same text in another article must not receive result');
assert.equal(imageA(), false);
assert.equal(imageA.signal.aborted, true, 'switching article aborts pending requests');
const imageB = scope.begin('image');
scope.update('article-b', '修改后');
assert.equal(imageB(), false, 'edited text must not receive old result');
assert.equal(imageB.signal.aborted, true, 'editing aborts the old network request');
scope.update('article-b', '原文');
assert.equal(imageB(), false, 'undo must not revive an obsolete request');
scope.update('article-b', '修改后');
const newImage = scope.begin('image');
scope.invalidate();
assert.equal(newImage(), false, 'cancel/unmount invalidates all pending results');
const resumed = scope.begin('layout');
assert.equal(resumed(), true, 'new requests work after invalidation');
scope.update('article-b', '修改后');
assert.equal(resumed(), true, 'unchanged render keeps pending request valid');
const plan = scope.begin('plan');
const independentImage = scope.begin('image:cover');
scope.cancel('plan');
assert.equal(plan(), false, 'cancel rejects pending results in the chosen channel');
assert.equal(independentImage(), true, 'cancelling a plan must not discard an independent image');
assert.equal(plan.signal.aborted, true);
assert.equal(independentImage.signal.aborted, false);
assert.equal(scope.begin('plan')(), true, 'generation can restart after channel cancellation');
const completed = scope.begin('completed');
completed.finish();
scope.invalidate();
assert.equal(completed.signal.aborted, false, 'completed work releases its controller');
const replaced = scope.begin('replace');
const replacement = scope.begin('replace');
replaced.finish();
assert.equal(replacement(), true, 'old completion cannot release a replacement request');
console.log('PASS: async scope isolates articles/text, keeps independent channels, rejects obsolete/cancelled requests');
